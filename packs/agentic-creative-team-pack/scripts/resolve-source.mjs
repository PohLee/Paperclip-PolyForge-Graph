import { spawn } from 'node:child_process';
import { stat, readFile, realpath } from 'node:fs/promises';
import { dirname, join, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { verifySourceSnapshot } from '../sources/integrity.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const [id,...parts]=process.argv.slice(2);
if(!id) throw new Error('Usage: node scripts/resolve-source.mjs <source-id> [tracked/path]');
const lock=JSON.parse(await readFile(join(root,'sources','upstream.lock.json'),'utf8'));
const source=lock.sources.find(s=>s.id===id); if(!source) throw new Error(`Unknown source id: ${id}`);
const snapshot=resolve(root,source.destination);
await new Promise((ok,no)=>{const p=spawn(process.execPath,[join(root,'scripts','materialize-sources.mjs'),id],{stdio:'inherit'});p.on('error',no);p.on('close',code=>code===0?ok():no(new Error(`materializer exited ${code}`)))});
const {path:realSnapshot}=await verifySourceSnapshot({root,source,snapshot});
const path=resolve(snapshot,...parts); const rel=relative(snapshot,path);
if(rel==='..'||rel.startsWith('..'+sep)) throw new Error('Requested path escapes snapshot');
const info=await stat(path); if(!info.isFile()&&!info.isDirectory()) throw new Error('Resolved source is not a file or directory');
const resolvedPath=await realpath(path), resolvedRel=relative(realSnapshot,resolvedPath);
if(resolvedRel==='..'||resolvedRel.startsWith('..'+sep)) throw new Error('Resolved source follows a symlink outside the snapshot');
console.log(resolvedPath);
